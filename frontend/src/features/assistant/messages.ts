/** Translator for request assembly and simple mode: Navis + common/widget names + every data string. */
const translators = new Map<Locale, Translator>();
export function navisTranslator(locale: Locale): Translator {
  let t = translators.get(locale);
  if (!t) {
    t = createTranslator(locale, ...([navisBundle, ...baseBundles, ...dataBundles] as unknown as MessageBundle<string>[]));
    translators.set(locale, t);
  }
  return t;
}
